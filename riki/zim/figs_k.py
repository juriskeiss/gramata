LAT_TOP, LAT_BOT = 84.0, -63.0
X0, Y0, SX = 10.0, 10.0, 760.0 / 360.0
SY = SX


def P(lon, lat):
    return X0 + (lon + 180.0) * SX, Y0 + (LAT_TOP - lat) * SY


def gc(a, b, n=24):
    """Lielā riņķa loka punkti starp a=(lon,lat) un b (garums var būt 'izvērsts' ārpus ±180)."""
    def v(lon, lat):
        lo, la = math.radians(lon), math.radians(lat)
        return (math.cos(la) * math.cos(lo), math.cos(la) * math.sin(lo), math.sin(la))
    p, q = v(*a), v(*b)
    om = math.acos(max(-1.0, min(1.0, sum(x * y for x, y in zip(p, q)))))
    out = []
    ref = a[0]
    for i in range(n + 1):
        t = i / n
        s1, s2 = math.sin((1 - t) * om) / math.sin(om), math.sin(t * om) / math.sin(om)
        x, y, z = (s1 * p[k] + s2 * q[k] for k in range(3))
        lon = math.degrees(math.atan2(y, x))
        while lon - ref > 180: lon -= 360
        while lon - ref < -180: lon += 360
        ref = lon
        out.append((lon, math.degrees(math.atan2(z, math.hypot(x, y)))))
    return out


