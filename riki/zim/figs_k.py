def _pts(poly, off):
    return " ".join("%.1f,%.1f" % P(lon + off, lat) for lon, lat in poly)


def _polys(polys, fill, stroke="none", sw=0.0):
    out = []
    for off in (-360, 0, 360):
        for p in polys:
            out.append(f'<polygon points="{_pts(p, off)}" fill="{fill}" stroke="{stroke}" '
                       f'stroke-width="{sw}" stroke-linejoin="round"/>')
    return "\n".join(out)


def _line(f, pts, color=K, w=1.1, dash="6 4"):
    for off in (-360, 0, 360):
        f.pl([P(lon + off, lat) for lon, lat in pts], dash=dash, w=w, color=color)


